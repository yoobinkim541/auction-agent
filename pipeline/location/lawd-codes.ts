function pick(table: Record<string, string>, addr: string): string | null {
  // 더 구체적인 키(긴 이름) 우선 매칭 — '일산동구'가 '동구'보다 먼저
  const keys = Object.keys(table).sort((a, b) => b.length - a.length);
  for (const k of keys) if (addr.includes(k)) return table[k]!;
  return null;
}

/** 주소 → LAWD_CD(5자리). 수도권 외/미매칭은 null. */
export function addressToLawdCd(address: string): string | undefined {
  const a = address.replace(/\s/g, '');
  if (a.includes('서울')) return pick(SEOUL, a) ?? undefined;
  if (a.includes('인천')) return pick(INCHEON, a) ?? undefined;
  // 경기 또는 시/도 표기가 생략된 경우 경기 테이블 시도
  return pick(GYEONGGI, a) ?? undefined;
}
