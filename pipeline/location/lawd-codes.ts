function pick(table: Record<string, string>, addr: string): string | null {
  // 더 구체적인 키(긴 이름) 우선 매칭 — '일산동구'가 '동구'보다 먼저
  const keys = Object.keys(table).sort((a, b) => b.length - a.length);
  for (const k of keys) if (addr.includes(k)) return table[k]!;
  return null;
}

/** 주소 → LAWD_CD(5자리). 수도권 외/미매칭은 null. */
export function addressToLawdCd(address: string): string | undefined {
  const a = address.replace(/\s/g, '');
  // '송내동' 안의 '내동'처럼 다른 이름에 묻힌 글자를 잡지 않도록 동은 낱말 단위로 맞춘다
  const words = address.split(/[\s(),]+/);
  // 시·도는 주소 머리에서만 읽는다 — '김포시 … 호텔마리나베이서울', '부천시 … 서울아파트'가 서울로 잡히지 않게.
  // ('사용본거지 : 경기도 …'처럼 머리말이 붙은 주소가 있어 앞 세 낱말까지 본다.)
  const sido = words.slice(0, 3).find((word) => /^(서울|인천|경기)/.test(word))?.slice(0, 2);
  if (sido === '서울') return pick(SEOUL, a) ?? undefined;
  if (sido === '인천') {
    const dongs = INCHEON_SPLIT[words.find((word) => INCHEON_SPLIT[word]) ?? ''];
    if (!dongs) return pick(INCHEON, a) ?? undefined;
    for (const word of words) {
      const code = dongs[word.replace(/\d+가$/, '')];
      if (code) return code;
    }
    return undefined;
  }
  // 경기 또는 시/도 표기가 생략된 경우 경기 테이블 시도
  const code = pick(GYEONGGI, a);
  if (code) return code;
  for (const [city, dongs] of Object.entries(DONG_TO_LAWD)) {
    if (!a.includes(city)) continue;
    for (const word of words) if (dongs[word]) return dongs[word];
  }
  return undefined;
}
